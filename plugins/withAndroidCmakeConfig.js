const {
  withAppBuildGradle,
  withDangerousMod,
  withProjectBuildGradle,
} = require("@expo/config-plugins");
const fs = require("fs");
const path = require("path");

const GENERATED_MARKER = "// Generated by plugins/withAndroidCmakeConfig.js";

const CMAKE_LISTS = [
  "cmake_minimum_required(VERSION 3.13)",
  "",
  "project(appmodules)",
  "",
  "set(CMAKE_CXX_STANDARD 20)",
  "set(CMAKE_CXX_EXTENSIONS OFF)",
  "",
  "link_libraries(c++_shared)",
  "",
  "include(${REACT_ANDROID_DIR}/cmake-utils/ReactNative-application.cmake)",
  "",
  "if(TARGET ${CMAKE_PROJECT_NAME})",
  "  target_link_libraries(${CMAKE_PROJECT_NAME} c++_shared)",
  "endif()",
  "",
].join("\n");

const SUBPROJECT_BLOCK = [
  "",
  GENERATED_MARKER,
  "rootProject.subprojects.each { subproj ->",
  '  ["com.android.library", "com.android.application"].each { pluginId ->',
  "    subproj.plugins.withId(pluginId) {",
  "      def extraArgs = [",
  '        "-DANDROID_STL=c++_shared",',
  '        "-DCMAKE_SHARED_LINKER_FLAGS=-lc++_shared",',
  '        "-DCMAKE_CXX_FLAGS=-std=gnu++20"',
  "      ]",
  "      try {",
  "        def cmakeExt1 = subproj.android?.defaultConfig?.externalNativeBuild?.cmake",
  "        if (cmakeExt1 != null) {",
  "          if (cmakeExt1.arguments == null) cmakeExt1.arguments = extraArgs else cmakeExt1.arguments += extraArgs",
  "        }",
  "      } catch (ignored) {}",
  "      try {",
  "        def cmakeExt2 = subproj.android?.externalNativeBuild?.cmake",
  "        if (cmakeExt2 != null) {",
  "          if (cmakeExt2.arguments == null) cmakeExt2.arguments = extraArgs else cmakeExt2.arguments += extraArgs",
  "        }",
  "      } catch (ignored) {}",
  "    }",
  "  }",
  "}",
  "",
].join("\n");

const APP_CMAKE_ARGS = [
  "        externalNativeBuild {",
  "            cmake {",
  '                cppFlags "-std=gnu++20"',
  '                arguments "-DANDROID_STL=c++_shared", "-DCMAKE_SHARED_LINKER_FLAGS=-lc++_shared", "-DCMAKE_CXX_FLAGS=-std=gnu++20", "-DCMAKE_OBJECT_PATH_MAX=1024"',
  "            }",
  "        }",
].join("\n");

const APP_CMAKE_PATH = [
  "    externalNativeBuild {",
  "        cmake {",
  '            path "src/main/jni/CMakeLists.txt"',
  "        }",
  "    }",
].join("\n");

function appendOnce(contents, marker, block) {
  if (contents.includes(marker)) {
    return contents;
  }
  return `${contents.trimEnd()}\n${block}`;
}

module.exports = function withAndroidCmakeConfig(config) {
  config = withDangerousMod(config, [
    "android",
    async (config) => {
      const jniDir = path.join(
        config.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "jni"
      );
      await fs.promises.mkdir(jniDir, { recursive: true });
      await fs.promises.writeFile(
        path.join(jniDir, "CMakeLists.txt"),
        CMAKE_LISTS,
        "utf8"
      );
      return config;
    },
  ]);

  config = withProjectBuildGradle(config, (config) => {
    config.modResults.contents = appendOnce(
      config.modResults.contents,
      GENERATED_MARKER,
      SUBPROJECT_BLOCK
    );
    return config;
  });

  config = withAppBuildGradle(config, (config) => {
    let contents = config.modResults.contents;

    if (!contents.includes('path "src/main/jni/CMakeLists.txt"')) {
      const compileSdkLine = /^(\s*compileSdk\s+rootProject\.ext\.compileSdkVersion\s*)$/m;
      if (!compileSdkLine.test(contents)) {
        throw new Error(
          "Could not find compileSdkVersion in android/app/build.gradle."
        );
      }
      contents = contents.replace(
        compileSdkLine,
        `$1\n${APP_CMAKE_PATH}`
      );
    }

    if (!contents.includes('cppFlags "-std=gnu++20"')) {
      const versionNameLine = /^(\s*versionName\s+".*")$/m;
      if (!versionNameLine.test(contents)) {
        throw new Error(
          "Could not find versionName in android/app/build.gradle."
        );
      }
      contents = contents.replace(
        versionNameLine,
        `$1\n${APP_CMAKE_ARGS}`
      );
    }

    config.modResults.contents = contents;
    return config;
  });

  return config;
};
